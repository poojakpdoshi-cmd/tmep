/**
 * Advanced SubStation Alpha (ASS) document builder.
 *
 * TMEP's motion layer compiles typography, captions, icons, charts and callouts into a
 * single ASS document rendered by libass inside the same FFmpeg pass that encodes the
 * video: no headless browser, no extra render pass, deterministic output, low RAM.
 * libass supports animated transforms (\t), movement (\move), fades, blur, clipping and
 * vector drawing (\p), which is enough for a professional short-form graphics package.
 */

export interface AssStyle {
  name: string;
  font: string;
  size: number;
  color?: string; // #RRGGBB primary
  outline?: string;
  back?: string;
  bold?: boolean;
  outlineW?: number;
  shadow?: number;
  align?: number; // numpad alignment
  borderStyle?: 1 | 3;
  spacing?: number;
}

export interface AssEvent {
  start: number;
  end: number;
  style: string;
  text: string;
  layer?: number;
}

/** #RRGGBB (+ optional alpha 0..1 opacity) -> &HAABBGGRR */
export function assColor(hex: string, opacity = 1): string {
  const h = hex.replace('#', '');
  const rr = h.slice(0, 2);
  const gg = h.slice(2, 4);
  const bb = h.slice(4, 6);
  const aa = Math.round((1 - opacity) * 255)
    .toString(16)
    .padStart(2, '0');
  return `&H${aa}${bb}${gg}${rr}`.toUpperCase();
}

/** Override-tag colour (\c&HBBGGRR&). */
export function tagColor(hex: string): string {
  const h = hex.replace('#', '');
  return `&H${h.slice(4, 6)}${h.slice(2, 4)}${h.slice(0, 2)}&`.toUpperCase();
}

export function tagAlpha(opacity: number): string {
  return `&H${Math.round((1 - opacity) * 255)
    .toString(16)
    .padStart(2, '0')
    .toUpperCase()}&`;
}

export function assTime(t: number): string {
  const cs = Math.max(0, Math.round(t * 100));
  const h = Math.floor(cs / 360000);
  const m = Math.floor((cs % 360000) / 6000);
  const s = Math.floor((cs % 6000) / 100);
  const c = cs % 100;
  return `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}.${String(c).padStart(2, '0')}`;
}

/** Escape user text for ASS dialogue (libass understands \{ \} \\). */
export function escapeText(s: string): string {
  return s.replace(/\\/g, '\\\\').replace(/\{/g, '\\{').replace(/\}/g, '\\}').replace(/\r?\n/g, '\\N');
}

export class AssDoc {
  readonly w: number;
  readonly h: number;
  private styles = new Map<string, AssStyle>();
  readonly events: AssEvent[] = [];

  constructor(w: number, h: number) {
    this.w = w;
    this.h = h;
  }

  style(s: AssStyle): string {
    this.styles.set(s.name, s);
    return s.name;
  }

  add(e: AssEvent): void {
    if (e.end > e.start) this.events.push(e);
  }

  toString(): string {
    const lines = [
      '[Script Info]',
      '; Generated by TMEP motion compiler',
      'ScriptType: v4.00+',
      `PlayResX: ${this.w}`,
      `PlayResY: ${this.h}`,
      'WrapStyle: 2',
      'ScaledBorderAndShadow: yes',
      'YCbCr Matrix: TV.709',
      '',
      '[V4+ Styles]',
      'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    ];
    for (const s of this.styles.values()) {
      lines.push(
        `Style: ${s.name},${s.font},${Math.round(s.size)},${assColor(s.color ?? '#FFFFFF')},${assColor(s.color ?? '#FFFFFF')},${assColor(s.outline ?? '#000000')},${assColor(s.back ?? '#000000', 0.55)},${s.bold ? -1 : 0},0,0,0,100,100,${s.spacing ?? 0},0,${s.borderStyle ?? 1},${s.outlineW ?? 0},${s.shadow ?? 0},${s.align ?? 5},0,0,0,1`,
      );
    }
    lines.push('', '[Events]', 'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text');
    const sorted = [...this.events].sort((a, b) => a.start - b.start || (a.layer ?? 0) - (b.layer ?? 0));
    for (const e of sorted) lines.push(`Dialogue: ${e.layer ?? 0},${assTime(e.start)},${assTime(e.end)},${e.style},,0,0,0,,${e.text}`);
    return `${lines.join('\n')}\n`;
  }
}

// ---------- easing helpers for \t acceleration ----------
/** \t accel parameter: <1 = ease-out (fast start), >1 = ease-in. */
export const EASE_OUT = 0.4;
export const EASE_IN = 2.2;

export function ms(t: number): number {
  return Math.max(0, Math.round(t * 1000));
}
